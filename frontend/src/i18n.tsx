export type Lang = "en" | "id";
const dictionaries: Record<Lang, Record<TKey, string>> = { en, id };

type Params = Record<string, string | number>;

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, params?: Params) => string;
}

const I18nContext = createContext<I18nValue>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

const stored = (): Lang => {
  try {
    return localStorage.getItem("oceda-lang") === "id" ? "id" : "en";
  } catch {
    return "en";
  }
};

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(stored);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("oceda-lang", l); } catch { /* ignore */ }
  };

  const t = (key: TKey, params?: Params) => {
    let s = dictionaries[lang][key] ?? en[key];
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
